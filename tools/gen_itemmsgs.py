#!/usr/bin/env python3
"""source/itemmsgs.h from UI Msg Get Item.prefab's Msg Control FSM: per item (the FSM's "Item" string) the texts of
the big item message (name, prefix, button description, two message lines) and the button it shows.
"""

import sys, os, json

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fsm_extract as F
from hkcommon import EX, metamap

p = f"{EX}/GameObject/UI Msg Get Item.prefab"
objs = F.load_objs(p)
P = F.Paths(objs)
fsm = None
for k, (t, v) in objs.items():
    if (
        t == "MonoBehaviour"
        and isinstance(v.get("fsm"), dict)
        and v["fsm"].get("name") == "Msg Control"
    ):
        fsm = F.decode_fsm(v, P, "")
st = {s["name"]: s for s in fsm["states"]}
init = st["Init"]
sw = [a for a in init["actions"] if a["type"].endswith("StringSwitch")][0]["params"]
items = sw["compareTo"]
evs = [e["event"] for e in sw["sendEvent"]]
tr = {t["event"]: t["to"] for t in init["transitions"]}
rows = []
for item, ev in zip(items, evs):
    s = st.get(tr.get(ev))
    if not s:
        continue
    if not any(
        a["type"].endswith("GetLanguageString") for a in s["actions"]
    ):  # e.g. "Fireball JA" -> "Set Fireball"
        s = st.get("Set " + item, s)
    texts = {}
    cur = None
    action = ""
    for a in s["actions"]:
        n = a["type"].split(".")[-1]
        pr = a["params"]
        if n == "GetLanguageString":
            cur = (pr.get("sheetName"), pr.get("convName"))
        elif n == "SetTextMeshProText" and cur:
            tgt = (pr.get("gameObject") or {}).get("var")
            texts[tgt] = cur
            cur = None
        elif n == "SendMessage":
            fc = pr.get("functionCall") or {}
            if fc.get("function") == "SetActionString":
                action = fc.get("s") or ""

    def q(k):
        v = texts.get(k)
        return ('"%s", "%s"' % v) if v else "NULL, NULL"

    rows.append(
        '    { "%s", %s, %s, %s, %s, %s, "%s" },'
        % (
            item,
            q("Item Name"),
            q("Item Name Prefix"),
            q("Press"),
            q("Msg 1"),
            q("Msg 2"),
            action,
        )
    )
out = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "source", "itemmsgs.h"
)
open(out, "w").write(
    "// generated by tools/gen_itemmsgs.py from UI Msg Get Item.prefab (Msg Control)\n"
    "typedef struct { const char *item, *nameSheet, *name, *prefixSheet, *prefix, *pressSheet, *press, *msg1Sheet, *msg1, *msg2Sheet, *msg2, *action; } ItemMsg;\n"
    "static const ItemMsg ITEM_MSGS[] = {\n" + "\n".join(rows) + "\n};\n"
)
print(len(rows), "items")
