#!/usr/bin/env python3
"""source/pd_defaults.h: PlayerData's new-game values (PlayerData.SetupNewPlayerData) for every non-zero int and
true bool, so FSMs asking for charmSlots, charmCost_N, nailDamage... get the game's numbers.
"""

import re, os

src = open(os.environ.get("HKDATA", "hkdata") + "/Assembly-CSharp/PlayerData.cs").read()
a = src.index("private void SetupNewPlayerData()")
b = src.index("\n\t}", a)
body = src[a:b]
rows = []
for name, val in re.findall(r"^\t\t(\w+) = ([^;]+);", body, re.M):
    val = val.strip()
    if val == "true":
        rows.append((name, 1, 1))
    elif re.fullmatch(r"-?\d+", val) and int(val) != 0:
        rows.append((name, int(val), 0))
seen = {}
for n, v, b_ in rows:
    seen[n] = (v, b_)  # last assignment wins
out = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "source", "pd_defaults.h"
)
open(out, "w").write(
    "// generated by tools/gen_pd_defaults.py from PlayerData.SetupNewPlayerData\n"
    "static const struct { const char *name; int v; bool isBool; } PD_DEFAULTS[] = {\n"
    + "".join(
        '    { "%s", %d, %s },\n' % (n, v, "true" if b_ else "false")
        for n, (v, b_) in sorted(seen.items())
    )
    + "};\n"
)
print(len(seen), "defaults")
