#!/usr/bin/env python3
"""source/journal_count.c: PlayerData.CountJournalEntries, translated from the game's decompiled script.
It's a list of `if (killed<X>) journalEntriesCompleted++;` / `if (kills<X> == 0) journalNotesCompleted++;` (and
journalEntriesTotal++ for the DLC entries); the Hunter's conversation reads the three results (GameManager.
CountJournalEntries) to decide whether the Journal is complete.
   HKDATA=... python tools/gen_journal_count.py"""

import os, re

ROOT = os.environ.get("HKDATA", "hkdata")
OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "source", "journal_count.c"
)
VARS = ("journalEntriesCompleted", "journalNotesCompleted", "journalEntriesTotal")

src = open(
    f"{ROOT}/Assembly-CSharp/PlayerData.cs", encoding="utf-8", errors="replace"
).read()
s = src.index("public void CountJournalEntries()")
b = src.index("{", s)
depth = 0
for k in range(b, len(src)):
    if src[k] == "{":
        depth += 1
    elif src[k] == "}":
        depth -= 1
        if depth == 0:
            e = k
            break
body = src[b + 1 : e]

# the function only tests killed<X> bools and kills<X> ints; anything else would need a hand port
for c in re.findall(r"if \(([^)]*)\)", body):
    if not re.fullmatch(r"killed\w+|kills\w+ == 0", c):
        raise SystemExit(f"unexpected condition: {c}")
for st in re.findall(r"^\s*([^{}\s][^\n]*;)\s*$", body, re.M):
    if not re.fullmatch(
        r"(%s) (=|\+=) \d+;|(%s)\+\+;" % ("|".join(VARS), "|".join(VARS)), st.strip()
    ):
        raise SystemExit(f"unexpected statement: {st}")

c = re.sub(r"\bkilled(\w+)", r'pd_bool("killed\1")', body)
c = re.sub(r"\bkills(\w+)", r'pd_int("kills\1")', c)
c = "\n".join(l[1:] if l.startswith("\t") else l for l in c.split("\n")).replace(
    "\t", "    "
)
out = (
    "// generated by tools/gen_journal_count.py from PlayerData.CountJournalEntries (do not edit)\n"
    '#include "pd.h"\n\n'
    "void journal_count_entries(void) {\n"
    f'    int {", ".join(VARS)};\n'
    + c.rstrip()
    + "\n"
    + "".join(f'    pd_set_int("{v}", {v});\n' for v in VARS)
    + "}\n"
)
open(OUT, "w").write(out)
print("wrote", OUT, len(out.splitlines()), "lines")
